'use strict';
const {test}=require('node:test'), assert=require('node:assert/strict'), fs=require('node:fs'), path=require('node:path');
const root=path.join(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const js=read('public/lux-match.js'),css=read('public/lux-match.css'),html=read('public/index.html');
test('SPEC111 : une carte, un logo de marque et les vraies données pédagogiques',()=>{
  const swipe=js.slice(js.indexOf('function lmRendreSwipe(box) {'),js.indexOf('function lmBoutonAide() {'));
  assert.match(swipe,/lmEntete\(\)/);
  assert.doesNotMatch(swipe,/class="lm-app-titre"/);
  assert.match(swipe,/class="lm-carte" id="lm-carte"/);
  assert.match(swipe,/class="lm-carte-visuel"/);
  assert.match(swipe,/lmImage\(profil, 'Idle', LM_FONDS\.carte, 'lm-carte-photo'\)/);
  assert.match(swipe,/lmLu\(t\.lu\) \+ lmFr\(t\.fr\)/);
  assert.match(swipe,/profil\.ton/);
  assert.match(swipe,/t\.tags\.map/);
  assert.match(swipe,/PROFIL ' \+ numero \+ ' \/ ' \+ total/);
  assert.match(swipe,/class="lm-carte-pile/);
  assert.match(swipe,/class="lm-tampon lm-tampon-oui">J’AIME/);
  assert.match(swipe,/class="lm-tampon lm-tampon-non">PASSER/);
  assert.match(swipe,/class="lm-rond-texte">PASSER/);
  assert.match(swipe,/class="lm-rond-texte">J’AIME/);
  assert.match(swipe,/onclick="lmSwiper\(true\)"/);
  assert.match(swipe,/onclick="lmSwiper\(false\)"/);
});
test('SPEC111 : seuils, rejets et garde double-clic conservés',()=>{
  assert.match(js,/const LM_SEUIL_SWIPE = 90/);
  assert.match(js,/const LM_SEUIL_SENS = 12/);
  assert.match(js,/pointercancel/);
  assert.match(js,/lostpointercapture/);
  assert.match(js,/lm\.swipeEnCours/);
  assert.match(js,/setTimeout\(\(\) => \{[\s\S]*?LuxMatchCore\.swiper\(lm\.partie, aime\)[\s\S]*?\}, 260\)/);
  assert.match(js,/carte\.style\.transform = ''; \/\/ la classe de sortie/);
});
test('SPEC111 : CSS limité au swipe et lecture accessible',()=>{
  const section=css.slice(css.indexOf('/* SPEC 111 —'),css.indexOf('/* Politique de scroll (SPEC §18.6)'));
  assert.ok(section.length>3000);
  assert.doesNotMatch(section,/#view-luxdemasque/);
  assert.match(section,/\.lm-jeu\[data-ecran="swipe"\] \.lm-carte-infos/);
  assert.match(section,/touch-action:pan-y/);
  assert.match(section,/font-size:16px/);
  assert.match(section,/prefers-reduced-motion:reduce/);
  assert.match(section,/\.lm-tel-swipe/);
  assert.match(html,/lux-match\.css\?v=22/);
  assert.match(html,/lux-match\.js\?v=29/);
  const jeux=read('public/jeux-v21.js');
  assert.match(jeux,/luxMatch:\s*false/);
});
